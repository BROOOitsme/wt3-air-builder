# ---------- Vehicle stub generation ----------

def build_vehicle_stub(vehicle_id, opts):
    """opts: dict of feature toggles + values."""
    lines = [
        f'include "#/develop/gameBase/gameData/units/tankModels/{vehicle_id}.blk"',
        "",
    ]
    
    if opts.get("weapon_override"):
        wo = opts["weapon_override"]
        lines += [
            f'"@override:weapon_presets" {{ "@override:preset[1]" {{ "@override:name":t = "{wo["preset_name"]}"}}}}',
            f'"@override:weapon_presets" {{ "@override:preset[1]" {{ "@override:blk":t = "{wo["preset_blk"]}"}}}}',
            "",
            f'"@override:commonWeapons" {{ "@override:Weapon[1]" {{ "@override:trigger":t = "gunner0"}}}}',
            f'"@override:commonWeapons" {{ "@override:Weapon[1]" {{ "@override:blk":t = "{wo["weapon_blk"]}"}}}}',
            "",
        ]
    
    if opts.get("engine_override"):
        eo = opts["engine_override"]
        lines += [
            f'"@override:VehiclePhys" {{ "@override:Mass" {{ "@override:Empty":r={eo.get("mass", 50000)}}}}}',
            f'"@override:VehiclePhys" {{ "@override:engine" {{ "@override:horsePowers":r={eo["hp"]}}}}}',
            f'"@override:VehiclePhys" {{ "@override:engine" {{ "@override:maxRPM":r={eo.get("max_rpm", 15000)}}}}}',
            f'"@override:VehiclePhys" {{ "@override:engine" {{ "@override:minRPM":r={eo.get("min_rpm", 3000)}}}}}',
            "",
        ]
    
    lines += [
        f"//Generated by wt3-native — base stub {BASE_STUB}",
        f"//Change '{BASE_STUB}' from line to any Tank ID",
    ]
    
    return "\n".join(lines)


# ---------- Weapon stub generation ----------

def build_weapon_stub(name, base_weapon_blk, overrides):
    """overrides: list of (kind, params) tuples."""
    lines = [
        f"// wt3-native custom weapon: {name}",
        f'include "#/develop/gameBase/{base_weapon_blk}"',
    ]
    
    for kind, params in overrides:
        if kind == "bullet_speed":
            lines.append(f'"@override:bullet" {{ "@override:speed":r={params["speed"]}}}')
        elif kind == "caliber":
            lines.append(f'"@override:bullet" {{ "@override:caliber":r={params["caliber"]}}}')
        elif kind == "mass":
            lines.append(f'"@override:bullet" {{ "@override:mass":r={params["mass"]} }}')
        elif kind == "explosive":
            lines.append(f'"@override:bullet" {{ "@override:explosiveMass":r={params["mass"]} }}')
        elif kind == "rapid_fire":
            lines.append(f'"@override:shotFreq":r={params["freq"]}')
            lines.append(f'reloadTime:r={1.0/params["freq"]}')
            lines.append(f'"@override:reloadTime":r={1.0/params["freq"]}')
            lines.append("bEnablePause:b=no")
            lines.append('"@override:bEnablePause":b=no')
            lines.append('"@override:recoilOffset":r=0.0')
            lines.append('"@override:recoilTimes":p2=0.01, 0.01')
            lines.append('"@override:bullet" { recoilMultiplier:r=0.0 }')
        elif kind == "weightless":
            lines.append('"@override:rocket" { "@override:dragCx":r = 0 }')
        elif kind == "rocket_speed":
            for field in ("startSpeed", "maxSpeed", "endSpeed"):
                lines.append(f'"@override:bullet" {{ "@override:rocket" {{ "@override:{field}":r={params["speed"]}}}}}')
                lines.append(f'"@override:rocket" {{ "@override:{field}":r={params["speed"]}}}')
    
    return "\n".join(lines) + "\n"


