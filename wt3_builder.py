def load_vehicles(kind):
    path = DB_DIR / f"{kind}.json"
    if not path.exists():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(data, dict) and "vehicles" in data:
        return data["vehicles"]
    if isinstance(data, list):
        return data
    return []


def all_vehicles():
    out = {}
    for k in ("ground", "air", "heli", "naval"):
        v = load_vehicles(k)
        if v:
            out[k] = v
    return out


def find_vehicle(vehicles, vehicle_id):
    for vs in vehicles.values():
        for v in vs:
            if v.get("id") == vehicle_id:
                return v
    return None


def collect_cannon_paths(vehicles):
    paths = {}
    for vs in vehicles.values():
        for v in vs:
            for w in v.get("weapons", []):
                blk = w.get("blk", "")
                if blk and "cannon" in blk.lower():
                    paths.setdefault(blk, set()).add(v.get("name", "?"))
    return paths


def build_cannon_ammo_index(vehicles):
    idx = {}
    for vs in vehicles.values():
        for v in vs:
            limits = v.get("ammoLimits", {})
            cannons = set()
            for w in v.get("weapons", []):
                blk = w.get("blk", "")
                if blk and "cannon" in blk.lower():
                    cannons.add(blk)
            for cannon_blk in cannons:
                bucket = idx.setdefault(cannon_blk, {})
                for a in v.get("ammo", []):
                    aid = a.get("id")
                    if not aid or aid in bucket:
                        continue
                    pool = a.get("pool", "")
                    bucket[aid] = {
                        "id": aid,
                        "name": a.get("name", aid),
                        "pool": pool,
                        "limit": limits.get(pool, 30),
                    }
    return {k: sorted(v.values(), key=lambda x: x["name"]) for k, v in idx.items()}


def collect_nations(vehicles):
    s = set()
    for vs in vehicles.values():
        for v in vs:
            n = v.get("nation")
            if n:
                s.add(n)
    return sorted(s)


def collect_classes(vehicles):
    s = set()
    for vs in vehicles.values():
        for v in vs:
            c = v.get("class")
            if c:
                s.add(c)
    return sorted(s)


def build_vehicle_stub(vehicle_id, features):
    lines = [f'include "#/develop/gameBase/gameData/units/tankModels/{vehicle_id}.blk"', ""]
    wo = features.get("weapon_override")
    if wo:
        preset = wo["preset_name"] or f"{vehicle_id}_default"
        preset_blk = wo.get("preset_blk") or f"gameData/units/tankmodels/{vehicle_id}.blk"
        lines += [
            f'"@override:weapon_presets" {{ "@override:preset[1]" {{ "@override:name":t = "{preset}"}}}}',
            f'"@override:weapon_presets" {{ "@override:preset[1]" {{ "@override:blk":t = "{preset_blk}"}}}}',
            "",
            f'"@override:commonWeapons" {{ "@override:Weapon[1]" {{ "@override:trigger":t = "gunner0"}}}}',
            f'"@override:commonWeapons" {{ "@override:Weapon[1]" {{ "@override:blk":t = "{wo["weapon_blk"]}"}}}}',
            "",
        ]
    eo = features.get("engine_override")
    if eo:
        lines += [
            f'"@override:VehiclePhys" {{ "@override:Mass" {{ "@override:Empty":r={eo["mass"]}}}}}',
            f'"@override:VehiclePhys" {{ "@override:engine" {{ "@override:horsePowers":r={eo["hp"]}}}}}',
            f'"@override:VehiclePhys" {{ "@override:engine" {{ "@override:maxRPM":r={eo["max_rpm"]}}}}}',
            f'"@override:VehiclePhys" {{ "@override:engine" {{ "@override:minRPM":r={eo["min_rpm"]}}}}}',
            "",
        ]
    lines += ["//Generated by wt3-native", f"//Change '{BASE_STUB}' from line to any Tank ID", ""]
    return "\n".join(lines)


def build_weapon_stub(name, base_weapon_blk, overrides):
    lines = [f"// wt3-native custom weapon: {name}", f'include "#/develop/gameBase/{base_weapon_blk}"']

    for kind, params in overrides:
        if kind == "bullet_speed":
            lines.append(f'"@override:bullets[0]" {{ "@override:speed":r={params["speed"]}}}')
        elif kind == "caliber":
            lines.append(f'"@override:bullets[0]" {{ "@override:caliber":r={params["caliber"]}}}')
        elif kind == "mass":
            lines.append(f'"@override:bullets[0]" {{ "@override:mass":r={params["mass"]} }}')
        elif kind == "explosive":
            lines.append(f'"@override:bullets[0]" {{ "@override:explosiveMass":r={params["mass"]} }}')
        elif kind == "no_recoil":
            lines += [
                'recoilMultiplier:r=0.0',
                'recoilOffset:r=0.0',
            ]
        elif kind == "rapid_fire":
            freq = params["freq"]
            lines += [
                f'"@override:shotFreq":r={freq}',
                f'reloadTime:r={round(1.0/freq, 4)}',
                f'"@override:reloadTime":r={round(1.0/freq, 4)}',
                "bEnablePause:b=no",
                '"@override:bEnablePause":b=no',
            ]

    return "\n".join(lines) + "\n"


def swap_unit_class(text, unit_name, new_class):
    pattern = rf'name:t="{re.escape(unit_name)}"((?:(?!name:t=)[\s\S])*?)unit_class:t="[^"]*"'
    replacement = rf'name:t="{unit_name}"\1unit_class:t="{new_class}"'
    return re.subn(pattern, replacement, text, count=1)


def set_respawn(text, unit_name, enabled, respawn_time):
    """Inject respawn:b=yes and respawnTime into the unit block."""
    if not enabled:
        return text, 0
    # Insert respawn lines right after the name:t line for the target unit.
    pattern = rf'(\bname:t="{re.escape(unit_name)}")'
    replacement = (
        rf'\1\n'
        rf'        respawn:b=yes\n'
        rf'        respawnTime:r={respawn_time}'
    )
    return re.subn(pattern, replacement, text, count=1)


def patch_mission(player_vehicle, targets, vehicles, player_ammo=None,
                  player_preset_override=None, aced=False, modules=False,
                  respawn=None):
    if not TEMPLATE.exists():
        raise FileNotFoundError(f"Template missing at {TEMPLATE}")

    text = TEMPLATE.read_text(encoding="utf-8")
    report = []

    text, n = swap_unit_class(text, "You", f"userVehicles/{BASE_STUB}")
    report.append(f"player -> userVehicles/{BASE_STUB} (real: {player_vehicle}) : {n}")

    vehicle = find_vehicle(vehicles, player_vehicle)
    preset = player_preset_override
    if not preset and vehicle:
        preset = vehicle.get("preset")
    if preset:
        pat = rf'(name:t="You"(?:(?!name:t=)[\s\S])*?weapons:t=")[^"]*(")'
        text, n2 = re.subn(pat, rf'\g<1>{preset}\g<2>', text, count=1)
        report.append(f"weapons preset -> {preset} : {n2}")

    if player_ammo:
        for slot, entry in player_ammo.items():
            ammo_id, count = entry
            pat_t = rf'(name:t="You"(?:(?!name:t=)[\s\S])*?bullets{slot}:t=")[^"]*(")'
            text, n3 = re.subn(pat_t, rf'\g<1>{ammo_id}\g<2>', text, count=1)
            pat_c = rf'(name:t="You"(?:(?!name:t=)[\s\S])*?bulletsCount{slot}:i=)\d+'
            text, n4 = re.subn(pat_c, rf'\g<1>{count}', text, count=1)
            report.append(f"ammo slot {slot} -> {ammo_id} x{count} : {n3}/{n4}")

    # Apply respawn settings once per unit name.
    respawn = respawn or {}
    respawn_time = respawn.get("time", 5.0)
    respawn_flags = respawn.get("flags", {})

    def apply_respawn(unit_name, key):
        if respawn_flags.get(key):
            return set_respawn(text, unit_name, True, respawn_time)

    for i in range(1, 6):
        tid = targets.get(f"ground{i}")
        if tid:
            text, n = swap_unit_class(text, f"Target_Ground_0{i}", tid)
            report.append(f"ground{i} -> {tid} : {n}")
            text, n = set_respawn(text, f"Target_Ground_0{i}", respawn_flags.get(f"ground{i}", False), respawn_time)
            if n:
                report.append(f"ground{i} respawn -> every {respawn_time}s : {n}")
    if targets.get("mover"):
        text, n = swap_unit_class(text, "Target_Ground_Mover", targets["mover"])
        report.append(f"mover -> {targets['mover']} : {n}")
        text, n = set_respawn(text, "Target_Ground_Mover", respawn_flags.get("mover", False), respawn_time)
        if n:
            report.append(f"mover respawn -> every {respawn_time}s : {n}")
    if targets.get("air"):
        text, n = swap_unit_class(text, "Target_Air_01", targets["air"])
        report.append(f"air -> {targets['air']} : {n}")
        text, n = set_respawn(text, "Target_Air_01", respawn_flags.get("air", False), respawn_time)
        if n:
            report.append(f"air respawn -> every {respawn_time}s : {n}")
    if targets.get("heli"):
        text, n = swap_unit_class(text, "Target_Heli_01", targets["heli"])
        report.append(f"heli -> {targets['heli']} : {n}")
        text, n = set_respawn(text, "Target_Heli_01", respawn_flags.get("heli", False), respawn_time)
        if n:
            report.append(f"heli respawn -> every {respawn_time}s : {n}")
    if targets.get("ship"):
        text, n = swap_unit_class(text, "Target_Ship_01", targets["ship"])
        report.append(f"ship -> {targets['ship']} : {n}")
        text, n = set_respawn(text, "Target_Ship_01", respawn_flags.get("ship", False), respawn_time)
        if n:
            report.append(f"ship respawn -> every {respawn_time}s : {n}")

    if aced:
        text = re.sub(r'(name:t="You"(?:(?!name:t=)[\s\S])*?)crewSkillK:r=[\d.]+',
                      r"\1crewSkillK:r=1", text, count=1)
        report.append("aced crew applied")
    if modules:
        text = re.sub(r'(name:t="You"(?:(?!name:t=)[\s\S])*?)applyAllMods:b=\w+',
                      r"\1applyAllMods:b=yes", text, count=1)
        report.append("research modules applied")

    BASE_MISSION.parent.mkdir(parents=True, exist_ok=True)
    BASE_MISSION.write_text(text, encoding="utf-8")
    return report


